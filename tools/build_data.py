"""Rebuild data.js, the data behind the site's grid-audit figures.

Everything comes from the grid audit's own data and code (jinnn11/grid-forecast-audit).
Run it from a checkout of that repository with its data in place:

    cd ~/code/grid-forecast-audit
    .venv/bin/python -I /path/to/website/tools/build_data.py /path/to/website/data.js

It reads data/processed/balance.parquet and the cached operator files through the
audit's functions, and writes only the output file.
"""

import json
import sys

sys.path.insert(0, "src")

import pandas as pd  # noqa: E402

from grid_audit import audit as A  # noqa: E402

YEAR = 2025


def number(v, decimals):
    text = f"{v:.{decimals}f}"
    return text.rstrip("0").rstrip(".") if "." in text else text


def array(values, decimals):
    return "[" + ",".join("null" if v is None else number(v, decimals) for v in values) + "]"


def daily_error(run, ba):
    """Total absolute error / total demand per local day, on the run's scored hours (%)."""
    h = run.hours[(run.hours["ba"] == ba) & (run.hours["year"] == YEAR)]
    g = h.assign(ae=(h["forecast"] - h["demand"]).abs()).groupby("day")
    by_day = g["ae"].sum() / g["demand"].sum() * 100
    days = pd.date_range(f"{YEAR}-01-01", f"{YEAR}-12-31", freq="D")
    return [None if pd.isna(v) else round(float(v), 2) for v in by_day.reindex(days)]


def main(out_path):
    hourly = pd.read_parquet(A.PARQUET_PATH)
    local = A.local_hours(hourly["local"])
    ba_events = A.read_events(A.EVENTS_PATH)

    # The main run, as all_runs() builds it, and the "All corrections" variant, as main() does
    main_rules = A.variant_rules(hourly, A.apply_rules(hourly, ba_events))["Main"]
    main_run = A.audit_run(hourly, local, main_rules)
    spp, charge = A.spp_forecast(), A.ciso_charging()
    moved, _ = A.verified_corrections(hourly, local, spp)
    table = A.charging_removed(moved, "CISO", A.moved_back(charge, A.CISO_LATE_SPANS))
    rules = {k: v for k, v in A.apply_rules(table, ba_events).rules.items() if k != "R3b"}
    corr_run = A.audit_run(table, local, rules)
    operators = sorted(main_run.yearly.xs(YEAR, level="year").index)

    # 1. Hourly demand: EIA's adjusted demand summed over the operators scored in YEAR
    in_year = (hourly["utc"] >= f"{YEAR}-01-01") & (hourly["utc"] < f"{YEAR + 1}-01-01")
    rows = hourly[in_year & hourly["ba"].isin(operators)]
    by_ba = rows.pivot(index="utc", columns="ba", values="demand_adjusted")
    missing = int(by_ba.isna().values.sum())
    filled = by_ba.copy()
    for _ in range(4):  # a missing hour takes the same hour a day earlier
        filled = filled.fillna(filled.shift(24))
    assert not filled.isna().values.any()
    demand = filled.sum(axis=1) / 1000
    twh = (filled.sum() / 1e6).round(2).sort_values(ascending=False)

    # 2. California ISO's average day, by local hour ending
    ciso = hourly["ba"].eq("CISO") & local["year"].eq(YEAR)
    hour = local.loc[ciso, "hour_ending"]
    day = pd.DataFrame({
        "hour": hour,
        "published": hourly.loc[ciso, "demand"],
        "forecast": hourly.loc[ciso, "forecast"],
        "corrected": table.loc[ciso, "demand"],
    }).dropna()
    mean = day.groupby("hour").mean() / 1000
    shift = pd.DataFrame({
        "hour": hour,
        "moved": moved.loc[ciso, "demand"],
        "published": hourly.loc[ciso, "demand"],
        "forecast": hourly.loc[ciso, "forecast"],
    }).dropna()
    mean_moved = (shift.groupby("hour")["moved"].mean() / 1000).round(2)

    lines = [
        "/* Chart data drawn from the grid audit's own data and code (jinnn11/grid-forecast-audit).",
        "   Generated by tools/build_data.py, not hand-edited; see README.md. */",
        "window.SITE_DATA = {",
        f"  // Hourly electricity demand in {YEAR}, GW: EIA-930 adjusted demand summed over the {len(operators)} operators",
        f"  // the audit scores. Hour 0 is {YEAR}-01-01 00:00 UTC. {missing} missing operator-hours (of {by_ba.size:,}) take",
        "  // the same hour a day earlier.",
        "  demand: " + array([round(v, 1) for v in demand.to_numpy()], 1) + ",",
        f"  // {YEAR} demand by operator, TWh",
        "  twh: " + json.dumps({k: float(v) for k, v in twh.items()}, separators=(",", ":")) + ",",
        f"  // California ISO, average {YEAR} day by local hour ending (1-24), GW: EIA-930 demand as published,",
        "  // the day-ahead forecast, demand moved back an hour (charging still in), and demand after all the audit's",
        "  // corrections (moved back an hour, battery charging out)",
        "  cisoDay: {moved: " + array(mean_moved.to_list(), 2)
        + ", published: " + array([round(v, 2) for v in mean["published"]], 2)
        + ", forecast: " + array([round(v, 2) for v in mean["forecast"]], 2)
        + ", corrected: " + array([round(v, 2) for v in mean["corrected"]], 2) + "},",
        f"  // Daily forecast error in {YEAR}, % (total absolute error / total demand on the scored hours), day 0 = 1 Jan;",
        "  // null where a day has no scored hours",
    ]
    for ba in ("SWPP", "CISO"):
        lines.append(f"  daily{ba}: {{published: " + array(daily_error(main_run, ba), 2)
                     + ", corrected: " + array(daily_error(corr_run, ba), 2) + "},")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(demand)} hours, peak {demand.max():.1f} GW, {missing} operator-hours filled")


if __name__ == "__main__":
    main(sys.argv[1])
